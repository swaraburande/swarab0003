from sklearn.metrics.pairwise import cosine_similarity

knowledge_base = [
    "Billing: Review invoices in Account Settings, Billing, and Invoices. Contact billing support about incorrect charges.",
    "Login: Use Forgot Password on the sign-in page. Check your spam folder and confirm you used the correct account email.",
    "Technical Issue: Refresh the page, update the app, and try again. Include steps to reproduce an error.",
    "Refund: Request a refund from Account Settings and Orders. Include your order ID.",
    "Feature Request: Describe the problem you want solved. The product team reviews suggestions."
]

knowledge_vectorizer = TfidfVectorizer(ngram_range=(1, 2))
knowledge_matrix = knowledge_vectorizer.fit_transform(knowledge_base)

def search_knowledge_base(query, top_k=3):
    query_vector = knowledge_vectorizer.transform([query])
    scores = cosine_similarity(query_vector, knowledge_matrix).flatten()
    best_indices = scores.argsort()[::-1][:top_k]

    return [
        knowledge_base[index]
        for index in best_indices
        if scores[index] > 0
    ]

search_knowledge_base("How do I reset my password?")

def generate_response(message, category, priority):
    results = search_knowledge_base(message, top_k=1)

    if results:
        answer = "Based on our support guide: " + results[0]
    else:
        answer = (
            f"Your request was classified as {category}. "
            f"Our {route_team(category)} team will review it."
        )

    if priority == "Urgent":
        answer += " This ticket has been marked urgent for prompt review."

    return (
        "Hello, thank you for contacting support. "
        + answer
        + " Please reply if you have more details."
    )

sample = "I need a refund for my order"
sample_category = classify_category(sample)
sample_priority = predict_priority(sample)

print(generate_response(sample, sample_category, sample_priority))

