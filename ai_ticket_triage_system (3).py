import re

def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"https?://\S+|www\.\S+", " URL ", text)
    text = re.sub(r"[^a-z0-9\s']", " ", text)
    return re.sub(r"\s+", " ", text).strip()

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline

category_model = Pipeline([
    ("tfidf", TfidfVectorizer(ngram_range=(1, 2))),
    ("classifier", LogisticRegression(max_iter=1000, random_state=42))
])

category_model.fit(tickets["customer_message"], tickets["category"])

def classify_category(message):
    return category_model.predict([message])[0]

def analyze_sentiment(message):
    text = clean_text(message)

    positive_words = ["thanks", "thank you", "great", "helpful", "excellent", "happy"]
    negative_words = ["angry", "terrible", "broken", "frustrated", "disappointed", "worst"]

    positive_score = sum(word in text for word in positive_words)
    negative_score = sum(word in text for word in negative_words)

    if positive_score > negative_score:
        return "Positive"
    if negative_score > positive_score:
        return "Negative"
    return "Neutral"

test_message = "I cannot log in and I am frustrated"
