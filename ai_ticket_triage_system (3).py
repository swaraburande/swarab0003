from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, f1_score, classification_report

X_train, X_test, y_train, y_test = train_test_split(
    tickets["customer_message"],
    tickets["category"],
    test_size=0.25,
    random_state=42,
    stratify=tickets["category"]
)

evaluation_model = Pipeline([
    ("tfidf", TfidfVectorizer(ngram_range=(1, 2))),
    ("classifier", LogisticRegression(max_iter=1000, random_state=42))
])

evaluation_model.fit(X_train, y_train)
category_predictions = evaluation_model.predict(X_test)

print("Category accuracy:", round(accuracy_score(y_test, category_predictions), 3))
print("Category macro F1:", round(f1_score(y_test, category_predictions, average="macro"), 3))
print(classification_report(y_test, category_predictions))

