# DAY 7 - Similar Ticket Search

import pandas as pd

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

df = pd.read_csv("tickets_clean.csv")

vectorizer = TfidfVectorizer(
    stop_words="english"
)

ticket_matrix = vectorizer.fit_transform(
    df["message"]
)

def find_similar_tickets(query, number=3):

    query_vector = vectorizer.transform(
        [query]
    )

    similarity_scores = cosine_similarity(
        query_vector,
        ticket_matrix
    ).flatten()

    indexes = similarity_scores.argsort()[
        -number:
    ][::-1]

    result = df.iloc[indexes][
        [
            "ticket_id",
            "message",
            "category",
            "priority"
        ]
    ].copy()

    result["similarity"] = similarity_scores[indexes]

    return result


query = "I cannot login to my account"

print(
    find_similar_tickets(query)
)

