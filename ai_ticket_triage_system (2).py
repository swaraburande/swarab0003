# DAY 3 - Text Cleaning and Category Classification

import pandas as pd
import re

from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression

df = pd.read_csv("tickets_clean.csv")

# Text cleaning function
def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()

df["clean_message"] = df["message"].apply(clean_text)

print("Cleaned messages:")
print(df[["message", "clean_message"]].head())

# TF-IDF
vectorizer = TfidfVectorizer(stop_words="english")

X = vectorizer.fit_transform(df["clean_message"])
y = df["category"]

# Train classification model
model = LogisticRegression(max_iter=2000)

model.fit(X, y)

print("\nCategory classifier trained successfully!")
print("Categories:")
print(model.classes_)

# Test
test_message = "My payment failed"

test_vector = vectorizer.transform(
    [clean_text(test_message)]
)

prediction = model.predict(test_vector)

print("\nTest Message:", test_message)
print("Predicted Category:", prediction[0])

