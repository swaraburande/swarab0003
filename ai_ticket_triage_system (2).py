# DAY 12 - Team Routing and Ticket Workflow

TEAM_MAP = {

    "Billing": "Finance",

    "Login": "Technical",

    "Refund": "Finance",

    "Technical Issue": "IT",

    "Feature Request": "Product"
}


def route_team(category):

    return TEAM_MAP.get(
        category,
        "General Support"
    )


def process_ticket(
    message,
    category,
    priority,
    sentiment
):

    team = route_team(
        category
    )

    ticket = {

        "message": message,

        "category": category,

        "priority": priority,

        "sentiment": sentiment,

        "team": team,

        "status": "Pending Human Review"
    }

    return ticket


result = process_ticket(
    "My payment failed",
    "Billing",
    "High",
    "Negative"
)

print("Processed Ticket:")
print(result)

