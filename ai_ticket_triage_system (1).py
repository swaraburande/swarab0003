def clean_text(text):
    text = str(text).lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


tickets_df["clean_message"] = tickets_df["message"].apply(clean_text)

# Split once, keeping the category proportions similar in both sets.
train_df, test_df = train_test_split(
    tickets_df,
    test_size=0.25,
    random_state=42,
    stratify=tickets_df["category"]
)

def create_model():
    return Pipeline([
        ("tfidf", TfidfVectorizer(ngram_range=(1, 2))),
        ("classifier", LogisticRegression(max_iter=1000))
    ])


# Train a separate model for category, priority, and sentiment.
models = {}

for target in ["category", "priority", "sentiment"]:
    model = create_model()
    model.fit(train_df["clean_message"], train_df[target])
    models[target] = model

