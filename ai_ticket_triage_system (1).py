solved_messages = [item["message"] for item in solved_tickets]

similarity_vectorizer = TfidfVectorizer(stop_words="english")
similarity_matrix = similarity_vectorizer.fit_transform(solved_messages)


def find_similar_tickets(message, limit=3):
    query = similarity_vectorizer.transform([message])
    scores = cosine_similarity(query, similarity_matrix)[0]
    best_indices = scores.argsort()[::-1][:limit]

    results = []
    for index in best_indices:
        if scores[index] > 0:
            item = solved_tickets[index]
            results.append(
                f'{item["id"]} | Similarity: {scores[index]:.2f}\n'
                f'Issue: {item["message"]}\n'
                f'Resolution: {item["resolution"]}'
            )

    return "\n\n".join(results) if results else "No similar tickets found."

