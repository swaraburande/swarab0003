def search_knowledge_base(message, limit=2):
    query = kb_vectorizer.transform([message])
    scores = cosine_similarity(query, kb_matrix)[0]
    best_indices = scores.argsort()[::-1][:limit]

    results = []
    for index in best_indices:
        if scores[index] > 0:
            item = knowledge_base[index]
            results.append(f'{item["title"]}: {item["text"]}')

    return "\n\n".join(results) if results else "No matching knowledge article found."

team_by_category = {
    "Billing": "Finance",
    "Refund": "Finance",
    "Login": "Technical",
    "Technical Issue": "IT",
    "Feature Request": "Product",
}


def create_response_draft(category, team, kb_result):
    if category == "Billing":
        opening = "We will review your payment and account records."
    if category == "Refund":
        opening = "We will review your refund request."
    if category == "Login":
        opening = "We will help you restore access to your account."
    if category == "Technical Issue":
        opening = "Our team will investigate the technical issue."
    if category == "Feature Request":
        opening = "Thank you for sharing your feature suggestion."
    else:
        opening = "Our support team will review your request."

    article_line = ""
    if kb_result != "No matching knowledge article found.":
        article_line = " Helpful information: " + kb_result.splitlines()[0]

    return (
        f"Hello, thank you for contacting support. {opening} "
        f"Our {team} team will follow up with you.{article_line}"
    )


ticket_store = []


def analyze_ticket(ticket_id, customer_info, message, status):
    if not message or not message.strip():
        return "Please enter a customer message.", make_ticket_table(), make_dashboard()

    if not ticket_id or not ticket_id.strip():
        ticket_id = f"TKT-{len(ticket_store) + 1001}"

    cleaned = clean_text(message)

    category = models["category"].predict([cleaned])[0]
    priority = models["priority"].predict([cleaned])[0]
    sentiment = models["sentiment"].predict([cleaned])[0]
    team = team_by_category.get(category, "Customer Support")

    similar_results = find_similar_tickets(message)
    kb_results = search_knowledge_base(message)
    response_draft = create_response_draft(category, team, kb_results)

    record = {
        "Ticket ID": ticket_id,
        "Date": str(date.today()),
        "Customer Information": customer_info or "Not provided",
        "Status":status,
        "Message": message,
        "Category": category,
        "Priority": priority,
        "Sentiment": sentiment,
        "Team": team,
    }

    # Update an existing ticket if its ID is reused.
    ticket_store[:] = [
        item for item in ticket_store
        if item["Ticket ID"] != ticket_id
    ]
    ticket_store.append(record)

    result = f"""
Ticket ID: {ticket_id}
Date: {record["Date"]}
Customer Information: {record["Customer Information"]}
Status: {status}

Category: {category}
Priority: {priority}
Sentiment: {sentiment}
Assigned Team: {team}

Similar Solved Tickets:
{similar_results}

Knowledge Base Results:
{kb_results}

Suggested Response Draft:
{response_draft}

A human support team member must review the draft before sending it.
"""
    return result, make_ticket_table(), make_dashboard()


def make_ticket_table():
    columns = [
        "Ticket ID", "Date", "Customer Information", "Message",
        "Category", "Priority", "Sentiment", "Team", "Status"
    ]
    return pd.DataFrame(ticket_store, columns=columns)


def make_dashboard():
    if not ticket_store:
        return "No tickets have been submitted yet."

    df = pd.DataFrame(ticket_store)
    category_counts = df["Category"].value_counts().to_string()
    status_counts = df["Status"].value_counts().to_string()

    return (
        f"Total tickets: {len(df)}\n"
        f"High or urgent tickets: "
        f"{int(df['Priority'].isin(['High', 'Urgent']).sum())}\n\n"
        f"Tickets by category:\n{category_counts}\n\n"
        f"Tickets by status:\n{status_counts}"
    )

